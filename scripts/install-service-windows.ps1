<#
.SYNOPSIS
    Volo-go Windows Service / Startup Task Installer & Manager (windows/amd64)

.DESCRIPTION
    Installs, upgrades, queries, or uninstalls Volo-go as a background system service on Windows.
    - Uses NSSM automatically when available on PATH, or registers an elevated Scheduled Startup Task
      running under NT AUTHORITY\NETWORK SERVICE with automatic restart-on-failure.
    - Locks down .env secrets via NTFS ACLs (icacls) so only Administrators, SYSTEM, and NETWORK SERVICE can read it.

.EXAMPLE
    powershell -ExecutionPolicy Bypass -File .\scripts\install-service-windows.ps1 -Action Install -BinaryPath .\volo.exe -PublicUrl "https://blog.example.com"
    powershell -ExecutionPolicy Bypass -File .\scripts\install-service-windows.ps1 -Action Status
    powershell -ExecutionPolicy Bypass -File .\scripts\install-service-windows.ps1 -Action Uninstall
#>

[CmdletBinding()]
param(
    [ValidateSet("Install", "Upgrade", "Uninstall", "Status")]
    [string]$Action = "Install",

    [string]$ServiceName = "VoloBlog",
    [string]$BinaryPath = ".\volo.exe",
    [string]$InstallDir = "C:\ProgramData\Volo",
    [string]$ListenAddr = "127.0.0.1:8080",
    [string]$PublicUrl = "http://localhost:8080",
    [string]$AdminPath = "/console",
    [string]$TrustedProxies = "127.0.0.1/32,::1/128",
    [switch]$OpenFirewallPort,
    [switch]$PurgeData,
    [switch]$DryRun
)

$ErrorActionPreference = "Stop"

$TargetBin = Join-Path $InstallDir "bin\volo.exe"
$EnvFile   = Join-Path $InstallDir "volo.env"
$DataDir   = Join-Path $InstallDir "data"
$LogDir    = Join-Path $InstallDir "logs"

function Invoke-Step([string]$Desc, [scriptblock]$Block) {
    if ($DryRun) {
        Write-Host "[dry-run] $Desc"
    } else {
        & $Block
    }
}

function New-RandomHex32 {
    $bytes = New-Object byte[] 32
    [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
    return ($bytes | ForEach-Object { $_.ToString("x2") }) -join ""
}

$NssmCmd = Get-Command "nssm.exe" -ErrorAction SilentlyContinue

switch ($Action) {
    { $_ -in @("Install", "Upgrade") } {
        if (-not $DryRun -and -not (Test-Path $BinaryPath)) {
            throw "Binary not found at '$BinaryPath'. Build or download volo.exe first."
        }

        foreach ($dir in @(
            (Join-Path $InstallDir "bin"),
            $DataDir,
            (Join-Path $DataDir "uploads"),
            (Join-Path $DataDir "backups"),
            (Join-Path $DataDir "geoip"),
            (Join-Path $InstallDir "plugins"),
            (Join-Path $InstallDir "themes"),
            (Join-Path $InstallDir "locales"),
            $LogDir
        )) {
            Invoke-Step "Ensure directory $dir" {
                New-Item -ItemType Directory -Force -Path $dir | Out-Null
            }
        }

        Invoke-Step "Copy $BinaryPath -> $TargetBin" {
            Copy-Item -Force -Path $BinaryPath -Destination $TargetBin
        }

        if (-not (Test-Path $EnvFile)) {
            $secret = New-RandomHex32
            $envContent = @"
# Generated by install-service-windows.ps1
VOLO_LISTEN_ADDR=$ListenAddr
VOLO_PUBLIC_URL=$PublicUrl
VOLO_TRUSTED_PROXIES=$TrustedProxies
VOLO_ADMIN_PATH=$AdminPath
VOLO_SECRET_KEY=$secret
VOLO_GEO_ACCESS_ENABLED=true

VOLO_DB_DRIVER=sqlite
VOLO_DB_DSN=$($DataDir -replace '\\','/')/volo.db

VOLO_DATA_DIR=$($DataDir -replace '\\','/')
VOLO_UPLOAD_DIR=$($DataDir -replace '\\','/')/uploads
VOLO_BACKUP_DIR=$($DataDir -replace '\\','/')/backups
VOLO_GEOIP_DIR=$($DataDir -replace '\\','/')/geoip
VOLO_PLUGINS_DIR=$($InstallDir -replace '\\','/')/plugins
VOLO_THEMES_DIR=$($InstallDir -replace '\\','/')/themes
VOLO_LOCALES_DIR=$($InstallDir -replace '\\','/')/locales
"@
            Invoke-Step "Write $EnvFile and restrict NTFS ACLs via icacls" {
                Set-Content -Path $EnvFile -Value $envContent -Encoding UTF8
                & icacls.exe $InstallDir /grant "NT AUTHORITY\NETWORK SERVICE:(OI)(CI)M" | Out-Null
                & icacls.exe $EnvFile /inheritance:r /grant:r "NT AUTHORITY\SYSTEM:F" "BUILTIN\Administrators:F" "NT AUTHORITY\NETWORK SERVICE:R" | Out-Null
            }
        }

        if ($NssmCmd) {
            Invoke-Step "Register & start Windows Service '$ServiceName' via NSSM" {
                if ($Action -eq "Upgrade") {
                    & $NssmCmd.Source stop $ServiceName 2>$null | Out-Null
                } else {
                    & $NssmCmd.Source install $ServiceName $TargetBin "serve --env-file `"$EnvFile`"" | Out-Null
                }
                & $NssmCmd.Source set $ServiceName AppDirectory $InstallDir | Out-Null
                & $NssmCmd.Source set $ServiceName AppStdout (Join-Path $LogDir "volo.out.log") | Out-Null
                & $NssmCmd.Source set $ServiceName AppStderr (Join-Path $LogDir "volo.err.log") | Out-Null
                & $NssmCmd.Source set $ServiceName Start SERVICE_AUTO_START | Out-Null
                & $NssmCmd.Source start $ServiceName | Out-Null
            }
        } else {
            Invoke-Step "Register & start Scheduled System Startup Task '$ServiceName' (NETWORK SERVICE)" {
                $taskAction = New-ScheduledTaskAction -Execute $TargetBin -Argument "serve --env-file `"$EnvFile`"" -WorkingDirectory $InstallDir
                $trigger    = New-ScheduledTaskTrigger -AtStartup
                $settings   = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -ExecutionTimeLimit ([TimeSpan]::Zero) -RestartCount 5 -RestartInterval (New-TimeSpan -Minutes 1)
                $principal  = New-ScheduledTaskPrincipal -UserId "NT AUTHORITY\NETWORK SERVICE" -LogonType ServiceAccount -RunLevel LeastPrivilege
                Register-ScheduledTask -TaskName $ServiceName -Action $taskAction -Trigger $trigger -Settings $settings -Principal $principal -Force | Out-Null
                Start-ScheduledTask -TaskName $ServiceName
            }
        }

        if ($OpenFirewallPort -and ($ListenAddr -match ":(\d+)$")) {
            $port = [int]$Matches[1]
            Invoke-Step "Add Windows Firewall inbound TCP rule on port $port" {
                New-NetFirewallRule -DisplayName "Volo-go HTTP ($port)" -Direction Inbound -Action Allow -Protocol TCP -LocalPort $port -ErrorAction SilentlyContinue | Out-Null
            }
        }

        Write-Host "Volo-go Windows service $Action completed ($InstallDir)."
    }

    "Status" {
        if ($NssmCmd -and (Get-Service -Name $ServiceName -ErrorAction SilentlyContinue)) {
            Invoke-Step "Query Windows Service '$ServiceName'" {
                Get-Service -Name $ServiceName | Format-List Name, Status, StartType
            }
        } else {
            Invoke-Step "Query Scheduled Task '$ServiceName'" {
                Get-ScheduledTask -TaskName $ServiceName | Get-ScheduledTaskInfo | Format-List *
            }
        }
    }

    "Uninstall" {
        if ($NssmCmd -and (Get-Service -Name $ServiceName -ErrorAction SilentlyContinue)) {
            Invoke-Step "Stop and remove NSSM Windows Service '$ServiceName'" {
                & $NssmCmd.Source stop $ServiceName 2>$null | Out-Null
                & $NssmCmd.Source remove $ServiceName confirm | Out-Null
            }
        } else {
            Invoke-Step "Stop and unregister Scheduled Task '$ServiceName'" {
                Stop-ScheduledTask -TaskName $ServiceName -ErrorAction SilentlyContinue
                Unregister-ScheduledTask -TaskName $ServiceName -Confirm:$false -ErrorAction SilentlyContinue
            }
        }
        if ($PurgeData) {
            Invoke-Step "Purge $InstallDir" {
                Remove-Item -Recurse -Force -Path $InstallDir -ErrorAction SilentlyContinue
            }
            Write-Host "Volo-go service and data purged."
        } else {
            Write-Host "Volo-go service removed. Data preserved in '$InstallDir'."
        }
    }
}
